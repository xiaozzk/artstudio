#!/usr/bin/env python3
"""Derive the `artwork` agent-preset bundle patch from the shipped `standard` patch.

Lives beside the bundle it generates: `python3 ~/.dsh/presets/artwork/derive.py`
rewrites cordis.patch.yml from whatever `standard.patch.yml` the installed dsh
currently ships, which is how this preset is refreshed after a dsh upgrade.

Every transformation is an exact literal replacement asserted to fire exactly once,
so the derived plugin list cannot silently drift from the latest standard preset.
"""
from pathlib import Path

STANDARD = Path(
    "/opt/homebrew/lib/node_modules/@deepseek-ai/dsh/node_modules/"
    "@deepseek-ai/dsh-web-app/presets/standard.patch.yml"
)
OUT = Path(__file__).resolve().parent / "cordis.patch.yml"

src = STANDARD.read_text(encoding="utf-8")


def sub(text: str, old: str, new: str) -> str:
    assert text.count(old) == 1, f"expected exactly one occurrence of:\n{old!r}\ngot {text.count(old)}"
    return text.replace(old, new)


# 1. header comment
src = sub(
    src,
    "# Agent preset standard: one `@deepseek-ai/dsh-agent-preset` declaration inserted\n"
    "# after the web patch. Edits saved from the Web editor override this row's\n"
    "# `config.plugins` by id from the profile patch.\n",
    "# Agent preset artwork (艺术创作): DERIVED FROM THE SHIPPED `standard` PRESET.\n"
    "#\n"
    "# Generated by the sibling derive.py (python3 derive.py) from\n"
    "#   @deepseek-ai/dsh-web-app/presets/standard.patch.yml\n"
    "# with exactly three deltas:\n"
    "#   1. loader row id `preset-standard` -> `preset-artwork`, config.id -> `artwork`\n"
    "#   2. display name / description / roster order\n"
    "#   3. persona text names the art-creation role\n"
    "#   4. one appended `mcp-blender` row (@deepseek-ai/dsh-mcp-client)\n"
    "# Everything else is byte-identical to the shipped standard plugin list, so\n"
    "# re-running the generator after a dsh upgrade refreshes this preset.\n"
    "#\n"
    "# Installed with plugin_manager `install_bundle`; the profile holds a dependency on\n"
    "# this directory, so the two files here are the live definition, not a copy.\n",
)

# 2. loader row id
src = sub(src, "    - id: preset-standard\n", "    - id: preset-artwork\n")

# 3. declaration fields
src = sub(
    src,
    "        id: standard\n        order: 1\n",
    "        id: artwork\n"
    "        name: 艺术创作\n"
    "        description: '面向艺术创作：在最新 standard 预设之上接入 Blender MCP（工具名 mcp__blender__*），"
    "用于建模 / 材质 / 灯光 / 渲染等 3D 创作流程。'\n"
    "        order: 5\n",
)

# 4. persona
src = sub(
    src,
    "              prefix: You are a coding agent powered by the {{model}} model.\n",
    "              prefix: >-\n"
    "                You are an art-creation agent powered by the {{model}} model.\n"
    "                You make artwork, 3D assets and art direction, and you drive Blender\n"
    "                through the mcp__blender__ tools when a task needs 3D work (the Blender\n"
    "                addon's socket server must be listening on localhost:9876).\n",
)

# 5. the Blender MCP row, appended to the end of the plugin list
src = src.rstrip("\n") + "\n" + """
          # ── MCP: Blender ────────────────────────────────────────────────────────────
          # mcp-for-blender (https://github.com/ahujasid/mcp-for-blender), installed at
          # /Users/zhenkunzhu/Desktop/project/dpharness/mcp-for-blender. Scoped to THIS
          # preset on purpose, so 标准模式 and every other preset stay blender-free; its
          # tools appear to the model as mcp__blender__<tool>. The row provides no
          # service, so it sits flat like the tool rows above and needs no `isolate`
          # realm.
          #
          # The Blender side is the addon's TCP socket server on localhost:9876, installed
          # at ~/Library/Application Support/Blender/5.2/scripts/addons/blender_mcp.py. It
          # auto-starts when the Blender GUI opens (Scene > MCP for Blender > Auto-Start
          # Server, default on); headless Blender must call bpy.ops.blendermcp.start_server().
          - id: mcp-blender
            name: '@deepseek-ai/dsh-mcp-client'
            config:
              serverName: blender
              transport: stdio
              # Absolute path on purpose: mcp-client merges its env over a *scrubbed*
              # ambient env, so a bare `uv`/`mcp-for-blender` would not resolve on PATH.
              command: /Users/zhenkunzhu/Desktop/project/dpharness/mcp-for-blender/.venv/bin/mcp-for-blender
              env:
                BLENDER_HOST: localhost
                BLENDER_PORT: '9876'
                # Telemetry consent is on by default upstream and its terms permit
                # training on the data; keep it off unless you deliberately opt in.
                DISABLE_TELEMETRY: 'true'
              # Blender build/render operations can run for minutes.
              toolCallTimeoutMs: 300000
              # The preset keeps mounting while Blender is closed: the entry logs the
              # failed first connect and reconnects, instead of failing the mount.
              failOnStartupError: false
"""

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(src, encoding="utf-8")
print(f"wrote {OUT} ({len(src.splitlines())} lines)")